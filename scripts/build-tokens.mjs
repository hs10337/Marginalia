/* ------------------------------------------------------------- scale table -- */

function buildScaleTable() {
  const rows = styles.map(([name, style]) => {
    const web = style.web.min === style.web.max
      ? `${style.web.min}px`
      : `${style.web.min}\u2013${style.web.max}px`;
    const notes = [
      style.italic ? "italic" : null,
      style.uppercase ? "uppercase" : null,
      style.ios.opticalSize !== undefined ? `opsz ${style.ios.opticalSize}` : null,
    ].filter(Boolean).join(", ");
    return `| \`${name}\` | ${tokens.family[style.family].$value} | ${tokens.weight[style.weight].$value} | ${style.ios.size}/${style.ios.lineHeight} | ${web}/${style.web.lineHeight} | \`${style.ios.textStyle}\` | ${notes || "\u2014"} |`;
  });

  return [
    "<!-- GENERATED by scripts/build-tokens.mjs from tokens/typography.json \u2014 do not edit. -->",
    "",
    "# Type scale",
    "",
    `${styles.length} semantic styles. iOS values are pt at the default Dynamic Type size (Large); web values are px, shown as a range where the style is fluid between ${tokens.fluid.minViewport}px and ${tokens.fluid.maxViewport}px viewports.`,
    "",
    "| Token | Family | Weight | iOS size/line | Web size/line | Dynamic Type anchor | Notes |",
    "| --- | --- | --- | --- | --- | --- | --- |",
    ...rows,
    "",
  ].join("\n");
}

/* ------------------------------------------------------------------ main --- */

writeFileSync(join(root, "platforms/web/typography.css"), buildCss());
writeFileSync(join(root, "platforms/ios/TypographyTokens.generated.swift"), buildSwift());
writeFileSync(join(root, "docs/specimen.html"), buildSpecimen());
writeFileSync(join(root, "docs/scale.md"), buildScaleTable());

