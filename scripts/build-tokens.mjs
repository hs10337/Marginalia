#!/usr/bin/env node
// Generates the platform typography files from tokens/typography.json.
// Run: node scripts/build-tokens.mjs   (no dependencies)

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const tokens = JSON.parse(readFileSync(join(root, "tokens/typography.json"), "utf8"));

const ROOT_FONT_SIZE = 16;
const styles = Object.entries(tokens.scale).filter(([key]) => !key.startsWith("$"));

const round = (n, places = 4) =>
  Number.parseFloat(n.toFixed(places)).toString();

const kebab = (name) =>
  name.replace(/\./g, "-").replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

const camel = (name) => {
  const parts = name.split(".");
  return parts
    .map((part, i) => (i === 0 ? part : part[0].toUpperCase() + part.slice(1)))
    .join("");
};

const pascal = (s) => s[0].toUpperCase() + s.slice(1);

/* ------------------------------------------------------------------ web ---- */

// A style whose min and max differ interpolates linearly between the two
// viewport bounds; anything else is a fixed rem value.
function webFontSize({ min, max }) {
  const minRem = `${round(min / ROOT_FONT_SIZE)}rem`;
  if (min === max) return minRem;
  const { minViewport, maxViewport } = tokens.fluid;
  const slope = (max - min) / (maxViewport - minViewport);
  const vw = round(slope * 100);
  const intercept = round((min - slope * minViewport) / ROOT_FONT_SIZE);
  return `clamp(${minRem}, ${intercept}rem + ${vw}vw, ${round(max / ROOT_FONT_SIZE)}rem)`;
}

function buildCss() {
  const out = [];
  out.push("/* GENERATED by scripts/build-tokens.mjs from tokens/typography.json — do not edit. */");
  out.push("");
  out.push(":root {");
  out.push("  /* families */");
  for (const [key, family] of Object.entries(tokens.family)) {
    out.push(`  --font-${key}: ${family.web.stack};`);
  }
  out.push("");
  out.push("  /* weights */");
  for (const [key, weight] of Object.entries(tokens.weight)) {
    out.push(`  --font-weight-${kebab(key)}: ${weight.$value};`);
  }
  out.push("");
  out.push("  /* tracking */");
  for (const [key, value] of Object.entries(tokens.tracking)) {
    if (key.startsWith("$")) continue;
    out.push(`  --tracking-${kebab(key)}: ${round(value.web)}em;`);
  }

  for (const [name, style] of styles) {
    const prefix = `--type-${kebab(name)}`;
    out.push("");
    if (style.$description) out.push(`  /* ${name} — ${style.$description} */`);
    else out.push(`  /* ${name} */`);
    out.push(`  ${prefix}-family: var(--font-${style.family});`);
    out.push(`  ${prefix}-size: ${webFontSize(style.web)};`);
    out.push(`  ${prefix}-line-height: ${style.web.lineHeight};`);
    out.push(`  ${prefix}-weight: var(--font-weight-${kebab(style.weight)});`);
    out.push(`  ${prefix}-tracking: var(--tracking-${kebab(style.tracking)});`);
  }
  out.push("}");
  out.push("");

  for (const [name, style] of styles) {
    const prefix = `--type-${kebab(name)}`;
    out.push(`.type-${kebab(name)} {`);
    out.push(`  font-family: var(${prefix}-family);`);
    out.push(`  font-size: var(${prefix}-size);`);
    out.push(`  line-height: var(${prefix}-line-height);`);
    out.push(`  font-weight: var(${prefix}-weight);`);
    out.push(`  letter-spacing: var(${prefix}-tracking);`);
    if (style.italic) out.push("  font-style: italic;");
    if (style.uppercase) out.push("  text-transform: uppercase;");
    if (style.family === "serif") out.push("  font-optical-sizing: auto;");
    out.push("}");
    out.push("");
  }
  return out.join("\n");
}

/* ------------------------------------------------------------------ iOS ---- */

const swiftTextStyle = {
  largeTitle: ".largeTitle",
  title1: ".title",
  title2: ".title2",
  title3: ".title3",
  headline: ".headline",
  body: ".body",
  callout: ".callout",
  subheadline: ".subheadline",
  footnote: ".footnote",
  caption1: ".caption",
  caption2: ".caption2",
};

function swiftLiteral(n) {
  return Number.isInteger(n) ? `${n}` : `${n}`;
}

function buildSwift() {
  const out = [];
  out.push("// GENERATED by scripts/build-tokens.mjs from tokens/typography.json — do not edit.");
  out.push("");
  out.push("import SwiftUI");
  out.push("");
  out.push("public extension TypographyToken {");

  for (const [name, style] of styles) {
    const ts = swiftTextStyle[style.ios.textStyle];
    if (!ts) throw new Error(`Unmapped iOS text style "${style.ios.textStyle}" on ${name}`);
    out.push("");
    if (style.$description) out.push(`    /// ${style.$description}`);
    out.push(`    static let ${camel(name)} = TypographyToken(`);
    out.push(`        name: "${name}",`);
    out.push(`        family: .${style.family},`);
    out.push(`        weight: .${style.weight},`);
    out.push(`        size: ${swiftLiteral(style.ios.size)},`);
    out.push(`        lineHeight: ${swiftLiteral(style.ios.lineHeight)},`);
    out.push(`        tracking: ${swiftLiteral(tokens.tracking[style.tracking].ios)},`);
    out.push(`        textStyle: ${ts},`);
    out.push(`        opticalSize: ${style.ios.opticalSize === undefined ? "nil" : swiftLiteral(style.ios.opticalSize)},`);
    out.push(`        isItalic: ${style.italic ? "true" : "false"},`);
    out.push(`        isUppercased: ${style.uppercase ? "true" : "false"}`);
    out.push("    )");
  }
  out.push("}");
  out.push("");

  // PostScript name tables, so the runtime never hard-codes a font file name.
  out.push("public extension TypographyToken.Family {");
  out.push("    /// PostScript names of the shipped font files, by weight and slant.");
  out.push("    func postScriptName(weight: TypographyToken.Weight, italic: Bool) -> String {");
  out.push("        switch self {");
  for (const [key, family] of Object.entries(tokens.family)) {
    const ps = family.ios.postScript;
    out.push(`        case .${key}:`);
    out.push("            switch (weight, italic) {");
    for (const weightKey of Object.keys(tokens.weight)) {
      const upright = ps[weightKey];
      const italicKey = weightKey === "regular" ? "italic" : `${weightKey}Italic`;
      const slanted = ps[italicKey] ?? upright;
      out.push(`            case (.${weightKey}, false): return "${upright}"`);
      out.push(`            case (.${weightKey}, true): return "${slanted}"`);
    }
    out.push("            }");
  }
  out.push("        }");
  out.push("    }");
  out.push("");
  out.push("    /// Family name as registered with the system, for diagnostics.");
  out.push("    var displayName: String {");
  out.push("        switch self {");
  for (const [key, family] of Object.entries(tokens.family)) {
    out.push(`        case .${key}: return "${family.$value}"`);
  }
  out.push("        }");
  out.push("    }");
  out.push("}");
  out.push("");
  return out.join("\n");
}

/* --------------------------------------------------------------- specimen -- */

function buildSpecimenRows() {
  return styles.map(([name, style]) => ({
    name,
    className: `type-${kebab(name)}`,
    family: tokens.family[style.family].$value,
    weight: tokens.weight[style.weight].$value,
    ios: style.ios,
    web: style.web,
    sizeCss: webFontSize(style.web),
  }));
}

